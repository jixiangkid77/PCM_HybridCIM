//============================================================
// amu_top.v   (P2R-E8.5, address-map unit)
//============================================================
// The whole address map of pcm_imc_unit: the shared entry
// computation (amu_entry), the per-lane check (amu_lanes), the
// controller with the buffer tags, the reading ahead and the
// ROM read and parking sequence (amu_core), the entry buffer of
// all tables (amu_buf, 8 slots), their parking flags
// (amu_pflags) and the 50 tables (amu_table: four r48 ROM
// macros, selection of the buffer word, hit / out-of-range
// logic) of the 25 lanes x SRAM / PCM side. Its outputs replace those of the 50 original
// decoders (rtl/src/sram_addr_decoder.v, pcm_addr_decoder.v).
// This module is what E8.5 synthesises (the ROM macros are black
// boxes there) and simulates at gate level for power.
//
// Parking words: function amu_park from rtl/e8/amu_park_A.vh or
// amu_park_B.vh (-DMODEL_B), generated by scripts/e8_5_park_words.py.
//
// Place  : rtl/e8/
// Status : NEW FILE.
//============================================================

`timescale 1ns/1ps

module amu_top #(
    parameter integer K          = 25,
    parameter integer ADDR_WIDTH = 16,
    parameter integer SRAM_TOTAL = 3074,
    parameter integer PCM_TOTAL  = 58396,
    parameter         DATA_DIR   = ""
)(
    input  wire                    clk,
    input  wire                    rst_n,
    input  wire [2:0]              layer_id,
    input  wire [K*ADDR_WIDTH-1:0] orig_addr_bus,
    input  wire                    start_req,
    input  wire [15:0]             sram_base,
    input  wire [15:0]             sram_size,
    input  wire [15:0]             pcm_base,
    input  wire [15:0]             pcm_size,
    output wire [K-1:0]            sram_hit,
    output wire [K-1:0]            sram_oor,
    output wire [K*ADDR_WIDTH-1:0] sram_pool_addr_bus,
    output wire [K-1:0]            pcm_hit,
    output wire [K-1:0]            pcm_oor,
    output wire [K*ADDR_WIDTH-1:0] pcm_pool_addr_bus,
    output wire                    start_go,
    output wire                    stall,
    output wire [31:0]             n_lookup_reads,
    output wire [31:0]             n_park_reads,
    output wire [31:0]             n_stall_cycles,
    output wire [31:0]             n_starts,
    output wire [2:0]              errors          // {queue, lane 0, mismatch}
);

`ifdef MODEL_B
    `include "amu_park_B.vh"
`else
    `include "amu_park_A.vh"
`endif

    wire        v0, is_fc;
    wire [11:0] e0;
    wire [8:0]  flat0, in_dim;
    wire [K-1:0] valid, mismatch;

    amu_entry U_ENTRY (
        .layer_id(layer_id), .a0(orig_addr_bus[15:0]),
        .v0(v0), .e0(e0), .flat0(flat0), .in_dim(in_dim), .is_fc(is_fc)
    );
    amu_lanes #(.K(K), .ADDR_WIDTH(ADDR_WIDTH)) U_LANES (
        .addr_bus(orig_addr_bus), .v0(v0), .flat0(flat0), .in_dim(in_dim),
        .is_fc(is_fc), .valid(valid), .mismatch(mismatch)
    );

    wire [3:0]   rom_clk, rom_cs;
    wire         rom_park, cap, ready, out_ok;
    wire [7:0]   cap_en;
    wire [3:0]   park_end;
    wire [9:0]   rom_addr;
    wire [K-1:0] lane_en;
    wire [1:0]   cap_m;
    wire [2:0]   cap_slot, cur_slot;
    wire         err_mismatch, err_lane0, err_queue;

    amu_core #(.K(K)) U_CORE (
        .clk(clk), .rst_n(rst_n),
        .layer_id(layer_id), .a0(orig_addr_bus[15:0]), .v0(v0), .e0(e0),
        .start_req(start_req), .mismatch(mismatch),
        .rom_clk(rom_clk), .rom_cs(rom_cs), .rom_park(rom_park), .rom_addr(rom_addr),
        .rom_lane_en(lane_en), .cap(cap), .cap_m(cap_m), .cap_slot(cap_slot),
        .cap_en(cap_en), .park_end(park_end),
        .cur_slot(cur_slot), .cur_ready(ready), .out_ok(out_ok),
        .start_go(start_go), .stall(stall),
        .n_lookup_reads(n_lookup_reads), .n_park_reads(n_park_reads),
        .n_stall_cycles(n_stall_cycles), .n_starts(n_starts),
        .err_mismatch(err_mismatch), .err_lane0(err_lane0), .err_queue(err_queue)
    );
    assign errors = {err_queue, err_lane0, err_mismatch};
    // a table shows the current entry only when it is in the buffer (no stale or unwritten word)
    wire [K-1:0] valid_q = valid & {K{out_ok}};

    // entry buffer of all 50 tables (table t = side*K + lane)
    wire [2*K*16-1:0]       bdin;
    wire [8*2*K*16-1:0]     bq;
    amu_buf #(.NT(2*K), .NSLOT(8)) U_BUF (.clk(clk), .cap_en(cap_en), .din(bdin), .q(bq));

    // parking flags of all 50 tables (amu_pflags), updated at each capture and parking end
    wire [4*2*K-1:0] pflags;
    wire [2*K-1:0]   bzero;
    wire [3:0]       cap_upd = {4{cap}} & (4'b0001 << cap_m);
    amu_pflags #(.NT(2*K)) U_PF (
        .clk(clk), .rst_n(rst_n), .cap_upd(cap_upd), .clr(park_end),
        .part({lane_en, lane_en}), .zero(bzero), .flags(pflags)
    );

    genvar gi, gs;
    generate
        for (gi = 0; gi < K; gi = gi + 1) begin: tab
            wire [8*16-1:0] w_s, w_p;          // the buffer words of this lane's SRAM / PCM table
            for (gs = 0; gs < 8; gs = gs + 1) begin: sl
                assign w_s[gs*16 +: 16] = bq[(gs*2*K + gi)*16 +: 16];
                assign w_p[gs*16 +: 16] = bq[(gs*2*K + K + gi)*16 +: 16];
            end
            assign bzero[gi]     = (bdin[gi*16 +: 16] != 16'hFFFF);
            assign bzero[K + gi] = (bdin[(K + gi)*16 +: 16] != 16'hFFFF);
            amu_table #(
                .LANE(gi), .SIDE(0), .TOTAL(SRAM_TOTAL), .DATA_DIR(DATA_DIR),
                .PARK0(amu_park(0, gi, 0)), .PARK1(amu_park(0, gi, 1)),
                .PARK2(amu_park(0, gi, 2)), .PARK3(amu_park(0, gi, 3))
            ) U_STAB (
                .rom_clk(rom_clk), .rom_cs(rom_cs), .rom_park(rom_park), .rom_addr(rom_addr),
                .lane_en(lane_en[gi]), .cap_m(cap_m),
                .pflag({pflags[3*2*K + gi], pflags[2*2*K + gi], pflags[2*K + gi], pflags[gi]}),
                .cur_slot(cur_slot), .words(w_s), .dsel(bdin[gi*16 +: 16]),
                .valid(valid_q[gi]), .base(sram_base), .size(sram_size),
                .hit(sram_hit[gi]), .pool_addr(sram_pool_addr_bus[gi*ADDR_WIDTH +: ADDR_WIDTH]),
                .oor_error(sram_oor[gi])
            );
            amu_table #(
                .LANE(gi), .SIDE(1), .TOTAL(PCM_TOTAL), .DATA_DIR(DATA_DIR),
                .PARK0(amu_park(1, gi, 0)), .PARK1(amu_park(1, gi, 1)),
                .PARK2(amu_park(1, gi, 2)), .PARK3(amu_park(1, gi, 3))
            ) U_PTAB (
                .rom_clk(rom_clk), .rom_cs(rom_cs), .rom_park(rom_park), .rom_addr(rom_addr),
                .lane_en(lane_en[gi]), .cap_m(cap_m),
                .pflag({pflags[3*2*K + K + gi], pflags[2*2*K + K + gi], pflags[2*K + K + gi], pflags[K + gi]}),
                .cur_slot(cur_slot), .words(w_p), .dsel(bdin[(K + gi)*16 +: 16]),
                .valid(valid_q[gi]), .base(pcm_base), .size(pcm_size),
                .hit(pcm_hit[gi]), .pool_addr(pcm_pool_addr_bus[gi*ADDR_WIDTH +: ADDR_WIDTH]),
                .oor_error(pcm_oor[gi])
            );
        end
    endgenerate

endmodule
