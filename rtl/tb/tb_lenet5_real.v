// ============================================================
// tb_lenet5_real.v
// ------------------------------------------------------------
// End-to-end MNIST accuracy test for LeNet-5 RTL inference,
// using REAL quantized weights/biases/images from Paper 1.
//
// This is the key verification required by Professor Namba:
//   "推論を、PyTorch を使わず、すべて RTLシミュレーションだけで"
//
// Flow:
//   1. $readmemh loads INT8 weights, INT32 biases, protection
//      bitmaps, per-layer RSHIFT values, and MNIST test images
//   2. RTL runs full inference (conv1 -> pool1 -> conv2 -> pool2
//      -> fc1 -> fc2 -> fc3 -> argmax) for each image
//   3. testbench compares RTL's predicted class against MNIST's
//      ground-truth label (NOT against PyTorch predictions)
//   4. reports accuracy = correct / NUM_IMAGES
//
// Required compile flags (see run_real_experiment.ps1):
//   -DLOAD_REAL_DATA
//   -Pweight_memory.DATA_DIR, bias_storage.DATA_DIR,
//    layer_desc_rom.DATA_DIR (all to rtl_inputs_A or _B)
//   -Ptb_lenet5_real.DATA_DIR (this testbench's own path)
//   -Ptb_lenet5_real.NUM_IMAGES (1..100)
//
// Performance:
//   ~10 sec wall-clock per inference on Icarus Verilog
//   100 images ~= 15-20 minutes
// ============================================================

`timescale 1ns / 1ps

module tb_lenet5_real;

    // =========================================================
    // Parameters (override from command line)
    // =========================================================
    parameter integer NUM_IMAGES = 100;

    // DATA_DIR_STR and MODEL_NAME_STR are provided by either:
    //  (1) sim/run_config.vh (generated by run_real_experiment.ps1), or
    //  (2) the fallback defaults below (for direct testbench invocation
    //      without the PowerShell script)
    //
    // This include-file approach avoids all shell-quoting headaches.
`ifdef USE_CONFIG_VH
    `include "run_config.vh"
`else
    `define DATA_DIR_STR "../data/rtl_inputs_A"
    `define MODEL_NAME_STR "A"
`endif
    parameter DATA_DIR   = `DATA_DIR_STR;
    parameter MODEL_NAME = `MODEL_NAME_STR;

    localparam DATA_W  = 8;
    localparam FADDR_W = 13;

    // =========================================================
    // DUT signals
    // =========================================================
    reg                         clk, rst_n, start;
    reg                         image_we;
    reg  [FADDR_W-1:0]          image_addr;
    reg  signed [DATA_W-1:0]    image_data;
    wire                        done;
    wire [3:0]                  predicted_class;

    lenet5_top #(.DATA_DIR(DATA_DIR)) dut (
        .clk(clk), .rst_n(rst_n), .start(start),
        .done(done), .predicted_class(predicted_class),
        .image_we(image_we),
        .image_addr(image_addr),
        .image_data(image_data)
    );

    // Clock
    initial clk = 0;
    always #5 clk = ~clk;

    // =========================================================
    // Storage for labels and image pixels.
    // Exact sizes (100 labels, 784 pixels per 28x28 MNIST image)
    // to keep $readmemh silent.
    // =========================================================
    reg [7:0] true_labels [0:99];    // exactly 100 MNIST labels
    reg [7:0] img_pixels  [0:783];   // exactly 28*28 = 784 pixels

    // =========================================================
    // Tracking
    // =========================================================
    integer correct;
    integer total;
    integer i, k;
    integer cyc;
    reg [3:0]  captured_class;
    integer    captured_cycles;
    reg [1023:0] filename;

    // =========================================================
    // Load one image from hex file into the DUT feature buffer
    // =========================================================
    task load_image_from_hex;
        input integer img_idx;
        integer px;
        begin
            $sformat(filename, "%0s/images/img_%03d.hex", DATA_DIR, img_idx);

            // DIAGNOSTIC: print the filename actually being loaded
            $display("    [LOAD DIAG] img_idx=%0d  filename=<%0s>",
                     img_idx, filename);

            // Clear staging buffer
            for (px = 0; px < 784; px = px + 1) img_pixels[px] = 8'd0;

            // Read 784 INT8 hex bytes
            $readmemh(filename, img_pixels);

            // DIAGNOSTIC: print middle-of-image pixels to confirm different images
            // MNIST left corner is always black (all -19), so sample center pixels
            // where digit pixels actually differ across images
            $display("    [LOAD DIAG] pixel[380..384] (row 13, center): %3d %3d %3d %3d %3d",
                     $signed(img_pixels[380]), $signed(img_pixels[381]),
                     $signed(img_pixels[382]), $signed(img_pixels[383]),
                     $signed(img_pixels[384]));
            $display("    [LOAD DIAG] pixel[400..404] (row 14, center): %3d %3d %3d %3d %3d",
                     $signed(img_pixels[400]), $signed(img_pixels[401]),
                     $signed(img_pixels[402]), $signed(img_pixels[403]),
                     $signed(img_pixels[404]));

            // Stream into DUT
            for (px = 0; px < 784; px = px + 1) begin
                @(negedge clk);
                image_we   = 1'b1;
                image_addr = px[FADDR_W-1:0];
                image_data = $signed(img_pixels[px]);
                @(posedge clk);
            end
            @(negedge clk);
            image_we   = 1'b0;
            image_addr = 0;
            image_data = 0;

            // DIAGNOSTIC: peek feature_buffer internal storage after load
            $display("    [FBUF DIAG] mem_A[380..384] = %3d %3d %3d %3d %3d",
                     $signed(dut.u_fbuf.mem_A[380]), $signed(dut.u_fbuf.mem_A[381]),
                     $signed(dut.u_fbuf.mem_A[382]), $signed(dut.u_fbuf.mem_A[383]),
                     $signed(dut.u_fbuf.mem_A[384]));
            $display("    [FBUF DIAG] mem_B[380..384] = %3d %3d %3d %3d %3d",
                     $signed(dut.u_fbuf.mem_B[380]), $signed(dut.u_fbuf.mem_B[381]),
                     $signed(dut.u_fbuf.mem_B[382]), $signed(dut.u_fbuf.mem_B[383]),
                     $signed(dut.u_fbuf.mem_B[384]));
            $display("    [FBUF DIAG] role_sel=%b (0=A is write, 1=B is write)",
                     dut.u_fbuf.role_sel);
        end
    endtask

    // =========================================================
    // Run one inference and capture result
    // =========================================================
    task run_one_inference;
        output [3:0]   class_out;
        output integer cycles_out;
        integer        local_cyc;
        begin
            @(negedge clk); start = 1'b1;
            @(posedge clk); @(negedge clk); start = 1'b0;

            local_cyc = 0;
            while (!done && local_cyc < 3000000) begin
                @(posedge clk);
                local_cyc = local_cyc + 1;
            end

            // Capture synchronously with done pulse still asserted
            class_out  = predicted_class;
            cycles_out = local_cyc;

            // Drain the done pulse
            @(negedge clk);
        end
    endtask

    // =========================================================
    // Main
    // =========================================================
    initial begin
        // Reset state
        rst_n      = 1'b0;
        start      = 1'b0;
        image_we   = 1'b0;
        image_addr = 0;
        image_data = 0;

        // NO $dumpvars by default (VCD would be huge).
        // Uncomment if you need waveforms for one image:
        //   $dumpfile("tb_lenet5_real.vcd");
        //   $dumpvars(0, tb_lenet5_real.dut);

        $display("============================================================");
        $display("  tb_lenet5_real : End-to-end MNIST accuracy (RTL only)");
        $display("    Model       : %0s", MODEL_NAME);
        $display("    DATA_DIR    : %0s", DATA_DIR);
        $display("    NUM_IMAGES  : %0d", NUM_IMAGES);
        $display("============================================================");

        #23;
        rst_n = 1'b1;
        #2;

        // Load ground-truth labels from hex file
        for (i = 0; i < 100; i = i + 1) true_labels[i] = 8'hff;
        $sformat(filename, "%0s/image_labels.hex", DATA_DIR);
        $display("[INFO] Loading ground-truth labels : %0s", filename);
        $readmemh(filename, true_labels);
        $display("[INFO] First 10 labels: %0d %0d %0d %0d %0d %0d %0d %0d %0d %0d",
                 true_labels[0], true_labels[1], true_labels[2],
                 true_labels[3], true_labels[4], true_labels[5],
                 true_labels[6], true_labels[7], true_labels[8],
                 true_labels[9]);

        // Reset counters
        correct = 0;
        total   = 0;

        // =======================================================
        // Main loop: run N inferences
        // =======================================================
        for (i = 0; i < NUM_IMAGES; i = i + 1) begin
            load_image_from_hex(i + 1);
            run_one_inference(captured_class, captured_cycles);

            // ===== DIAGNOSTIC: print all 10 logits for the first 3 images =====
            if (i < 3) begin
                $display("    [DIAG] img_%03d logits from logit_rf:", i+1);
                $display("      logit[0..4] = %6d %6d %6d %6d %6d",
                         $signed(dut.u_logit_rf.mem[0]),
                         $signed(dut.u_logit_rf.mem[1]),
                         $signed(dut.u_logit_rf.mem[2]),
                         $signed(dut.u_logit_rf.mem[3]),
                         $signed(dut.u_logit_rf.mem[4]));
                $display("      logit[5..9] = %6d %6d %6d %6d %6d",
                         $signed(dut.u_logit_rf.mem[5]),
                         $signed(dut.u_logit_rf.mem[6]),
                         $signed(dut.u_logit_rf.mem[7]),
                         $signed(dut.u_logit_rf.mem[8]),
                         $signed(dut.u_logit_rf.mem[9]));
            end

            total = total + 1;
            if (captured_class == true_labels[i][3:0]) begin
                correct = correct + 1;
                $display("  img_%03d: RTL=%0d  true=%0d  cycles=%0d  [OK]",
                         i+1, captured_class, true_labels[i], captured_cycles);
            end else begin
                $display("  img_%03d: RTL=%0d  true=%0d  cycles=%0d  [MISS]",
                         i+1, captured_class, true_labels[i], captured_cycles);
            end

            // Running accuracy every 10 images
            if (((i + 1) % 10) == 0) begin
                $display("    --- running accuracy after %0d images: %0d/%0d = %.2f%% ---",
                         i+1, correct, total, (correct * 100.0) / total);
            end
        end

        // =======================================================
        // Final summary
        // =======================================================
        $display("");
        $display("============================================================");
        $display("  FINAL RESULT -- Model %0s", MODEL_NAME);
        $display("============================================================");
        $display("    RTL accuracy : %0d / %0d = %.2f%%",
                 correct, total, (correct * 100.0) / total);
        $display("    Data source  : %0s", DATA_DIR);
        $display("    Comparison   : RTL predictions vs MNIST ground-truth labels");
        $display("    PyTorch used : NO (inference runs entirely in Verilog)");
        $display("============================================================");

        $finish;
    end

    // Hard timeout safety net: (100 images) x (~2M cycles) x (10ns) = ~2 sec
    // plus I/O overhead. Real wall-clock limit is much larger -- Icarus has
    // no strict time limit, so we rely on the while-loop cycle bound instead.
    // But add a belt-and-braces:
    initial begin
        // 10 seconds of simulated time is way beyond 100 images
        #10000000000;
        $display("[ERROR] Hard simulated-time timeout!");
        $finish;
    end

endmodule
