#!/usr/bin/env python3
"""
preprocess_synth_rtl.py

Generate synthesis-ready RTL under rtl/synth/ by stripping simulation-only
system tasks from rtl/src/ files. Yosys can then read rtl/synth/*.v without
encountering $display, $readmemh path lookups, or other sim-only quirks
that confuse the parser/elaborator.

Pipeline (per file):
  rtl/src/<module>.v
    -> strip $display(...)    -> /* $display stripped for synth */
    -> strip $readmemh(...)   -> /* $readmemh stripped for synth */
    -> strip $finish          -> /* $finish stripped */
    -> strip $dumpfile, $dumpvars
    -> emit rtl/synth/<module>.v with auto-generated header

Modules NOT processed (use rtl/stub/ instead):
  - Large memory macros (their stubs are simpler than even-stripped source):
      pcm_crossbar, sram_addr_decoder, pcm_addr_decoder,
      sram_pool_25lane, feature_buffer
  - Legacy / ablation-only files not in Paper 2 hierarchy:
      weight_memory, weight_memory_drift, sram_pool (single-lane variant)

NOTE: this script does NOT touch rtl/src/. Functional simulation
(Step 9/10) continues to use rtl/src/ and is unaffected.

Encoding note (2026-05-12 patch):
  All file I/O is explicitly UTF-8. On Chinese-locale Windows the default
  is GBK, which fails on UTF-8 characters like em-dash in rtl/src/
  headers. Forcing UTF-8 here makes the script portable.
"""

import argparse
import os
import re
import sys


# Modules that use rtl/stub/ instead of rtl/synth/
SKIP_MODULES = {
    # Large memory / macro - use stubs
    'pcm_crossbar.v',
    'sram_addr_decoder.v',
    'pcm_addr_decoder.v',
    'sram_pool_25lane.v',
    'feature_buffer.v',
    # Legacy / ablation files not in current Paper 2 hierarchy
    'weight_memory.v',
    'weight_memory_drift.v',
    'sram_pool.v',
}

# Header to prepend to each generated file
def make_header(src_name):
    return (
        '//============================================================\n'
        f'// {src_name}\n'
        '// AUTO-GENERATED by scripts/preprocess_synth_rtl.py\n'
        '// DO NOT EDIT. Edit the source under rtl/src/ instead.\n'
        '//\n'
        '// This is the synthesis-only version with simulation system\n'
        '// tasks stripped ($display, $readmemh, $finish, $dumpfile,\n'
        '// $dumpvars). Functional behaviour is otherwise identical to\n'
        '// rtl/src/. Used by Yosys flow only; iverilog simulation uses\n'
        '// rtl/src/ directly.\n'
        '//============================================================\n'
    )


def strip_simonly(content):
    """Remove simulation-only system task calls.

    A call must be `$taskname(...);` or (for $finish) `$taskname;`.
    Any other occurrence (e.g., in a comment or string) is left alone.
    """
    def strip_call(text, taskname):
        out = []
        i = 0
        pattern = f'${taskname}'
        plen = len(pattern)
        n = len(text)
        while i < n:
            idx = text.find(pattern, i)
            if idx < 0:
                out.append(text[i:])
                break
            # Check next char isn't alphanumeric/underscore (avoid $displayfoo)
            after = idx + plen
            if after < n and (text[after].isalnum() or text[after] == '_'):
                out.append(text[i:idx + 1])
                i = idx + 1
                continue
            # Skip whitespace after the token
            j = after
            while j < n and text[j] in ' \t':
                j += 1
            # The call MUST be followed by '(' (real call) or ';' (e.g., $finish;)
            # If followed by anything else (e.g., '.', '/', '\n', word char),
            # it's a comment/string/something else — leave intact.
            if j >= n or text[j] not in '(;':
                # Not a real call; advance past the token unchanged
                out.append(text[i:after])
                i = after
                continue
            out.append(text[i:idx])
            if text[j] == ';':
                # Bare-form call (only valid for $finish)
                out.append(f'/* ${taskname} stripped */')
                i = j + 1
                continue
            # text[j] == '(' — match balanced parens
            depth = 1
            k = j + 1
            while k < n and depth > 0:
                if text[k] == '(':
                    depth += 1
                elif text[k] == ')':
                    depth -= 1
                k += 1
            # Skip optional whitespace + ';'
            while k < n and text[k] in ' \t\n\r':
                k += 1
            if k < n and text[k] == ';':
                k += 1
            out.append(f'/* ${taskname}(...) stripped */')
            i = k
        return ''.join(out)

    for task in ('display', 'readmemh', 'finish', 'dumpfile', 'dumpvars',
                 'write', 'monitor', 'strobe', 'fatal', 'error', 'warning',
                 'info'):
        content = strip_call(content, task)
    return content


def preprocess_file(src_path, dst_path, src_name):
    with open(src_path, encoding='utf-8') as f:
        content = f.read()

    new_content = strip_simonly(content)
    header = make_header(src_name)

    with open(dst_path, 'w', encoding='utf-8') as f:
        f.write(header + new_content)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--src-dir', default='rtl/src',
                        help='Source RTL directory (default: rtl/src)')
    parser.add_argument('--dst-dir', default='rtl/synth',
                        help='Output synthesis RTL directory (default: rtl/synth)')
    parser.add_argument('--verbose', action='store_true')
    args = parser.parse_args()

    if not os.path.isdir(args.src_dir):
        print(f'ERROR: source dir not found: {args.src_dir}', file=sys.stderr)
        sys.exit(2)
    os.makedirs(args.dst_dir, exist_ok=True)

    processed = []
    skipped = []
    n_stripped_total = 0

    for fname in sorted(os.listdir(args.src_dir)):
        if not fname.endswith('.v'):
            continue
        if fname in SKIP_MODULES:
            skipped.append(fname)
            continue
        src = os.path.join(args.src_dir, fname)
        dst = os.path.join(args.dst_dir, fname)

        # Count strips for diagnostics
        with open(src, encoding='utf-8') as f:
            orig = f.read()
        new = strip_simonly(orig)
        n_stripped = (
            new.count('/* $display(...) stripped */') +
            new.count('/* $readmemh(...) stripped */') +
            new.count('/* $finish stripped */') +
            new.count('/* $finish(...) stripped */') +
            new.count('/* $dumpfile(...) stripped */') +
            new.count('/* $dumpvars(...) stripped */')
        )
        n_stripped_total += n_stripped

        preprocess_file(src, dst, fname)
        processed.append((fname, n_stripped))

    print('preprocess_synth_rtl.py')
    print(f'  src dir : {args.src_dir}')
    print(f'  dst dir : {args.dst_dir}')
    print()
    print(f'Processed {len(processed)} files (total {n_stripped_total} sim-only calls stripped):')
    for fname, n in processed:
        marker = f'  ({n} stripped)' if n > 0 else ''
        print(f'  {args.dst_dir}/{fname}{marker}')
    print()
    print(f'Skipped {len(skipped)} files (use rtl/stub/ stubs instead):')
    for f in skipped:
        print(f'  {f}')


if __name__ == '__main__':
    main()
